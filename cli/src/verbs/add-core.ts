/** Hook name must be lower-kebab (parallels SKILL/AGENT/MCP/IDENTITY patterns). */
const HOOK_NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/;

/** The six portable events a hook can fire on (mirrors VALID_HOOK_EVENTS). */
const HOOK_EVENTS = [
  "SessionStart",
  "SessionEnd",
  "PreToolUse",
  "PostToolUse",
  "PreCompact",
  "PostCompact",
] as const;
type HookCoreEvent = (typeof HOOK_EVENTS)[number];

/** The 2 hook harness target types (mirrors VALID_HOOK_TARGET_TYPES). */
const HOOK_TARGET_TYPES = ["claude", "opencode"] as const;
type HookCoreTargetType = (typeof HOOK_TARGET_TYPES)[number];

interface CoreHookTarget {
  type: HookCoreTargetType;
  method: "merge";
  enabled?: boolean;
}

/** Parse one `type:merge[:enabled]` hook target spec (mirrors parseCoreMcpTarget). */
function parseCoreHookTarget(spec: string): CoreHookTarget | string {
  const parts = spec.split(":");
  if (parts.length < 2 || parts.length > 3) {
    return `--target '${spec}' must be of the form type:merge[:enabled]`;
  }
  const [type, method, enabledRaw] = parts;
  if (!(HOOK_TARGET_TYPES as readonly string[]).includes(type)) {
    return `--target type '${type}' is not one of ${JSON.stringify(HOOK_TARGET_TYPES)}`;
  }
  if (method !== "merge") {
    return `--target method '${method}' must be 'merge'`;
  }
  const t: CoreHookTarget = { type: type as HookCoreTargetType, method: "merge" };
  if (enabledRaw !== undefined) {
    if (enabledRaw !== "true" && enabledRaw !== "false") {
      return `--target '${spec}' enabled flag must be 'true' or 'false'`;
    }
    t.enabled = enabledRaw === "true";
  }
  return t;
}

/** The core hook block shape written into surfaces.hooks[]. */
interface CoreHookCanonical {
  command: string;
  matcher?: string;
  timeout?: number;
}
interface CoreHookBlock {
  name: string;
  event: HookCoreEvent;
  layer: "core";
  canonical: CoreHookCanonical;
  targets: CoreHookTarget[];
}

/** Options for {@link addCoreHook}. */
export interface AddCoreHookOptions {
  /** Hook name (lower-kebab). */
  name?: string;
  /** Repo root (the igris-ai checkout). */
  projectRoot: string;
  /** The event the hook fires on (required). */
  event?: string;
  /** Tool-name glob for Pre/PostToolUse (optional). */
  matcher?: string;
  /** Per-hook timeout in seconds (optional). */
  timeout?: number;
  /** Hook target specs, each `type:merge[:enabled]` (default claude:merge). */
  targets?: string[];
  /** Test seam: brain root override (defaults to brainDir()). */
  brainRoot?: string;
  /** Test seam: skip the runtime mirror + verify_mirror step. Default false. */
  skipMirror?: boolean;
}

/** Scaffold body for a core hook script. Executable; a no-op pass-through. */
function coreHookScriptScaffold(name: string, event: string): string {
  return `#!/usr/bin/env bash
# Core Igris hook '${name}' for the ${event} event.
# Generated by \`igris add --core hook ${name} --event ${event}\`. Replace the
# body below with the hook's real behavior; this script ships in the brain-core
# tarball and runs on every install that registers the hook.
set -euo pipefail

# TODO: implement the ${event} hook for '${name}'.
exit 0
`;
}

/**
 * FR-180 (Phase 5): materialize a new CORE event-hook. A core hook is BOTH:
 *   1. a shared SCRIPT at `core/hooks/shared/<event>.sh` (+ TD-096 runtime
 *      mirror) — the script the harness runs;
 *   2. a `surfaces.hooks[]` block in `core/scripts/cli-adapters/
 *      surfaces-manifest.json` (+ TD-096 mirror) — the GLOBAL Layer-1 surfaces
 *      file `flatten_hook_rows` unions when the project OWNS it. The block's
 *      `canonical.command` points at `$HOME/.igris/core/hooks/shared/<event>.sh`
 *      so the projector merges THAT path into the harness config.
 *
 * NOTE on event-vs-name: the shared script is keyed by EVENT (parity with the
 * existing canonical hooks: session_start.sh, pre_tool_use.sh, …). A core hook
 * `add` writes/reuses `core/hooks/shared/<event>.sh` and registers a NAMED block
 * pointing at it. If a script for that event already exists (the canonical set),
 * we REUSE it (no clobber) and only add the surfaces block.
 *
 * Refuses to clobber a `hooks` block of the same name (a re-add to core should
 * be an explicit edit — parity with the skill/agent/mcp/identity core writers).
 *
 * TD-096: the shared script + the surfaces manifest are both `core/` files with
 * a runtime mirror → both are cp'd + verify_mirror.sh'd.
 */
export function addCoreHook(opts: AddCoreHookOptions): AddCoreResult {
  const root = opts.brainRoot ?? brainDir();
  const manifestSource = join(
    opts.projectRoot,
    "core",
    "scripts",
    "cli-adapters",
    "surfaces-manifest.json",
  );
  const manifestMirror = join(
    root,
    "core",
    "scripts",
    "cli-adapters",
    "surfaces-manifest.json",
  );

  const fail = (code: number, reason: string, verifyOutput = ""): AddCoreResult => ({
    ok: false,
    code,
    reason,
    sourcePath: manifestSource,
    mirrorPath: manifestMirror,
    verifyOutput,
  });

  // --- Guards (all BEFORE any disk write). ----------------------------------
  if (opts.name === undefined || opts.name.length === 0) {
    return fail(2, "hook <name> is required");
  }
  if (!HOOK_NAME_PATTERN.test(opts.name)) {
    return fail(2, `name '${opts.name}' must match /^[a-z0-9][a-z0-9-]*$/`);
  }
  const name = opts.name;

  if (opts.event === undefined || opts.event.length === 0) {
    return fail(2, `hook '${name}': --event <${HOOK_EVENTS.join("|")}> is required`);
  }
  if (!(HOOK_EVENTS as readonly string[]).includes(opts.event)) {
    return fail(
      2,
      `hook '${name}': --event '${opts.event}' is not one of ${JSON.stringify(HOOK_EVENTS)}`,
    );
  }
  const event = opts.event as HookCoreEvent;

  const targetSpecs =
    opts.targets !== undefined && opts.targets.length > 0
      ? opts.targets
      : ["claude:merge"];
  const targets: CoreHookTarget[] = [];
  const seenTypes = new Set<string>();
  for (const spec of targetSpecs) {
    const parsed = parseCoreHookTarget(spec);
    if (typeof parsed === "string") {
      return fail(2, `hook '${name}': ${parsed}`);
    }
    if (seenTypes.has(parsed.type)) {
      return fail(2, `hook '${name}': duplicate --target type '${parsed.type}'`);
    }
    seenTypes.add(parsed.type);
    targets.push(parsed);
  }

  if (!existsSync(manifestSource)) {
    return fail(
      1,
      `core surfaces manifest not found at ${manifestSource}; not an igris-ai checkout`,
    );
  }

  // --- Parse the manifest + collision-check BEFORE the write. ---------------
  let manifest: {
    surfaces?: {
      hooks?: Array<{ name?: string; event?: string; targets?: { type?: string }[] }>;
    } & Record<string, unknown>;
  } & Record<string, unknown>;
  try {
    manifest = JSON.parse(readFileSync(manifestSource, "utf-8"));
  } catch (err) {
    return fail(1, `failed to parse ${manifestSource}: ${(err as Error).message}`);
  }
  const surfaces = (manifest.surfaces ?? {}) as {
    hooks?: CoreHookBlock[];
  } & Record<string, unknown>;
  const existing = Array.isArray(surfaces.hooks) ? surfaces.hooks : [];
  if (existing.some((h) => h.name === name)) {
    return fail(
      1,
      `core hook '${name}' already declared in ${manifestSource}; edit it directly (no clobber)`,
    );
  }
  // (event, target type) cell collision across existing blocks.
  const seenCells = new Set<string>();
  for (const b of existing) {
    for (const t of b.targets ?? []) {
      seenCells.add(`${b.event} ${t.type}`);
    }
  }
  for (const t of targets) {
    const cell = `${event} ${t.type}`;
    if (seenCells.has(cell)) {
      return fail(
        1,
        `core hook cell (${event}, ${t.type}) already declared in ${manifestSource}; ` +
          "two hooks must not both own the same event in the same harness",
      );
    }
  }

  // --- 1. Write/reuse the shared script. ------------------------------------
  const scriptSource = join(
    opts.projectRoot,
    "core",
    "hooks",
    "shared",
    `${event}.sh`,
  );
  const scriptMirror = join(root, "core", "hooks", "shared", `${event}.sh`);
  if (!existsSync(scriptSource)) {
    try {
      mkdirSync(dirname(scriptSource), { recursive: true });
      writeFileSync(scriptSource, coreHookScriptScaffold(name, event), {
        encoding: "utf-8",
        mode: 0o755,
      });
    } catch (err) {
      return fail(1, `failed to write core hook script: ${(err as Error).message}`);
    }
  }

  // --- 2. Build + append the surfaces block. --------------------------------
  const canonical: CoreHookCanonical = {
    command: `$HOME/.igris/core/hooks/shared/${event}.sh`,
  };
  if (opts.matcher !== undefined && opts.matcher.length > 0) {
    canonical.matcher = opts.matcher;
  }
  if (opts.timeout !== undefined) {
    canonical.timeout = opts.timeout;
  }
  const block: CoreHookBlock = { name, event, layer: "core", canonical, targets };
  surfaces.hooks = [...existing, block];
  manifest.surfaces = surfaces;
  try {
    writeFileSync(manifestSource, `${JSON.stringify(manifest, null, 2)}\n`, "utf-8");
  } catch (err) {
    return fail(1, `failed to update ${manifestSource}: ${(err as Error).message}`);
  }

  if (opts.skipMirror === true) {
    return {
      ok: true,
      code: 0,
      reason: "",
      sourcePath: manifestSource,
      mirrorPath: manifestMirror,
      verifyOutput: "(mirror skipped)",
    };
  }

  // --- TD-096 mirror + verify BOTH core/ files (the script + the manifest). --
  const verifyParts: string[] = [];
  const mirrors: Array<{ src: string; dst: string; label: string }> = [
    { src: scriptSource, dst: scriptMirror, label: "core/hooks/shared script" },
    { src: manifestSource, dst: manifestMirror, label: "core surfaces-manifest.json" },
  ];
  for (const m of mirrors) {
    const mv = mirrorAndVerify(m.src, m.dst, root);
    verifyParts.push(`# ${m.label}\n${mv.output}`);
    if (!mv.ok) {
      return fail(1, mv.reason, verifyParts.join("\n"));
    }
    info(`Mirror verified (${m.src} <-> ${m.dst}): MATCH`);
  }

  return {
    ok: true,
    code: 0,
    reason: "",
    sourcePath: manifestSource,
    mirrorPath: manifestMirror,
    verifyOutput: verifyParts.join("\n"),
  };
}
